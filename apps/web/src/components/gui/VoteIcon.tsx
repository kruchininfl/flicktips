const RENDER = { super: renderSuper, like: renderLike, neutral: renderNeutral, dislike: renderDislike };

interface VoteIconProps {
  // 0 - dislike, 1 - neutral, 2 - like, 3 - super (same ids as the API)
  vote: number;
  active?: boolean;
  className?: string;
}

export function VoteIcon({ vote, active = false, className }: VoteIconProps) {
  const name = NAMES[vote];
  if (!name) return null;

  return (
    <span className={cx('vote-icn', `vote-icn_${name}`, active && 'm-active', className)}>{RENDER[name](active)}</span>
  );
}
